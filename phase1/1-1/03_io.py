"""
1. 名前を受け取って挨拶する

input() で名前を入力してもらい、以下のように表示する

名前を入力してください: Ryota
こんにちは、Ryotaさん！
"""

name = input("名前を入力してください: ")
print(f"こんにちは、{name}さん！")

"""
2. 2つの整数を受け取って和を表示する

1つ目の数を入力: 5
2つ目の数を入力: 3
合計: 8
"""
num1, num2 = int(input("1つ目の数を入力: ")), int(input("2つ目の数を入力: "))
print(f"合計: {num1 + num2}")

"""
3. print() の sep と end を使う

以下の出力になるように sep と end を使って1行で書く

りんご/みかん/ぶどう（改行なし）←ここに続けて表示

通常の print() との違いを確認すること
"""
print("りんご", "みかん", "ぶどう", sep="/", end="")
