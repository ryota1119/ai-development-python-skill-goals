import numpy as np

# テーマ：スライス・インデックス操作

# 1. 1次元のスライス
# - a = np.arange(10)（[0 1 2 ... 9]）を作り
# - 前3つ a[:3] / 後ろ3つ a[-3:] / 1個飛ばし a[::2] を出力

a = np.arange(10)
print(a)

print(a[:3])
print(a[-3:])
print(a[::2])

# 2. 2次元のインデックス
# - m = np.arange(12).reshape(3, 4)（3×4）を作り
# - 1要素 m[1, 2]（2行3列目）/ 1行まるごと m[0] / 1列まるごと m[:, 1] を出力
# - 👉 Ruby/PHP の2次元配列は m[1][2] だが、NumPy は m[1, 2]
# とカンマ区切りで書ける点に注目

m = np.arange(12).reshape(3, 4)
print(m)

print(m[1, 2])
print(m[0])
print(m[:, 1])

# 3. 部分行列のスライス
# - m から「最初の2行 × 最後の2列」を切り出す（m[:2, 2:] のような書き方）

new_m = m[:2, 2:]
print(new_m)

# 4. ブールインデックス（NumPyらしい操作）
# - a から「5より大きい要素だけ」を取り出す
# - ヒント：a[a > 5] と書ける。a > 5 単体を print すると何が返るかも確認してみて

print(a > 5)
print(a[a > 5])
