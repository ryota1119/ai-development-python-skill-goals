import numpy as np

# テーマ：ブール索引（条件による抽出）

# 1. 比較演算でブール配列を作る
# - a = np.array([12, 7, 25, 3, 18, 30, 9]) を作る
# - a >= 10 を出力して、True/False の配列になることを確認する

a = np.array([12, 7, 25, 3, 18, 30, 9])

print(a >= 10)

# 2. 条件で要素を抽出する
# - a[a >= 10] で「10以上の要素だけ」を取り出して出力する

print(a[a >= 10])

# 3. 複数条件を組み合わせる（AND / OR）
# - 「10以上 かつ 20未満」の要素を抽出して出力する
# - 「5未満 または 25以上」の要素を抽出して出力する

print(a[(a >= 10) & (a < 20)])
print(a[(a < 5) | (a >= 25)])

# 4. 条件に合う要素を書き換える
# - a のうち「10未満の要素」を 0 に置き換えて、配列全体を出力する

new_a = np.where(a < 10, 0, a)
print(new_a)

a[a < 10] = 0
print(a)
